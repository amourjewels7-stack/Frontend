/* ============================================================
   AMOUR JEWELS — Tax invoice
   The invoice is generated by the backend as a PDF
   (GET /api/orders/{id}/invoice — only the order's owner may fetch it).
   This page fetches it with the signed-in session and shows it, so the
   numbers on screen are always exactly the ones on the official document.
   ============================================================ */
const invEsc = s => String(s == null ? '' : s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

async function renderInvoice() {
  const root = document.getElementById('invRoot');
  if (!root) return;
  const actions = document.querySelector('.inv-actions');
  if (actions) actions.hidden = true;
  const say = html => { root.innerHTML = `<div style="padding:40px 8px;text-align:center">${html}</div>`; };

  if (!AmourAuth.require()) return;                      /* → login.html?next=invoice.html?order=… */
  const number = (new URLSearchParams(location.search).get('order') || '').trim().toUpperCase();
  say('<p class="sub-hint">Preparing your invoice…</p>');
  try {
    const orders = await loadMyOrders();
    const o = number ? orders.find(x => x.id.toUpperCase() === number) : orderVisibleFirst(orders);
    if (!o) { say(`<p>We couldn’t find ${number ? 'order <b>' + invEsc(number) + '</b>' : 'an order'} on your account.</p><p><a class="btn" href="orders.html">Your Orders</a></p>`); return; }
    if (!o.paid) { say(`<p>Order <b>${invEsc(o.id)}</b> has not been paid, so there is no invoice yet.</p><p><a class="btn" href="orders.html">Your Orders</a></p>`); return; }

    const blob = await AmourAPI.invoice(o._id);
    const url = URL.createObjectURL(blob);
    root.innerHTML = `
      <div style="text-align:center;padding:8px 0 18px">
        <h1 style="font-size:22px;font-weight:500;letter-spacing:.06em;text-transform:uppercase">Tax Invoice</h1>
        <p class="sub-hint" style="margin-top:6px">Order ${invEsc(o.id)}</p>
        <div style="display:flex;gap:12px;justify-content:center;flex-wrap:wrap;margin-top:16px">
          <a class="btn" href="${url}" download="Amour-Invoice-${invEsc(o.id)}.pdf">Download PDF</a>
          <a class="btn ghost" href="${url}" target="_blank" rel="noopener">Open in new tab</a>
          <a class="btn ghost" href="orders.html">Your Orders</a>
        </div>
      </div>
      <iframe title="Invoice ${invEsc(o.id)}" src="${url}" style="width:100%;height:min(80vh,900px);border:1px solid var(--line-soft);border-radius:var(--r);background:#fff"></iframe>`;
  } catch (e) {
    if (e && e.status === 401) return;
    say(`<p>${invEsc(e.message || 'We could not load your invoice.')}</p><p><a class="btn" href="invoice.html${number ? '?order=' + encodeURIComponent(number) : ''}">Try again</a></p>`);
  }
}
const orderVisibleFirst = orders => orders.filter(orderVisible).find(o => o.paid);

window.addEventListener('amour:signedout', () => location.replace('login.html?next=' + encodeURIComponent('invoice.html' + location.search)));
amourReady(renderInvoice);
